#!/usr/bin/env python3
"""Build an Arch Linux package (.pkg.tar.xz) from a staged tree without makepkg or pacman.

usage: mkarch.py <staged-root> <output.pkg.tar.xz> --name N --version V [--pkgrel 1] --desc D --url U
                 [--license MIT] [--depend X ...] [--optdepend 'x: why' ...] [--install script]

The archive starts with .PKGINFO (metadata), .INSTALL (scriptlets) and .MTREE (what `pacman -Qkk` checks), then
the files.  Works on any distribution, so the package can be built anywhere and installed with `pacman -U`."""

from __future__ import annotations

import argparse
import gzip
import hashlib
import io
import os
import stat
import sys
import tarfile
import time


def _mtree(root: str, entries: list[tuple[str, str]], now: int, extra: dict[str, bytes]) -> bytes:
    lines = ["#mtree", "/set type=file uid=0 gid=0 mode=644"]

    def esc(p: str) -> str:
        return "".join(c if c.isalnum() or c in "/._-+@" else "\\%03o" % ord(c) for c in p)

    for name, data in extra.items():
        lines.append("./%s time=%d.0 size=%d sha256digest=%s" % (name, now, len(data),
                                                                  hashlib.sha256(data).hexdigest()))
    for full, rel in entries:
        st = os.lstat(full)
        if stat.S_ISDIR(st.st_mode):
            lines.append("./%s time=%d.0 mode=%o type=dir" % (esc(rel), now, stat.S_IMODE(st.st_mode)))
        elif stat.S_ISLNK(st.st_mode):
            lines.append("./%s time=%d.0 mode=777 type=link link=%s" % (esc(rel), now, esc(os.readlink(full))))
        else:
            with open(full, "rb") as fh:
                digest = hashlib.sha256(fh.read()).hexdigest()
            mode = stat.S_IMODE(st.st_mode)
            lines.append("./%s time=%d.0%s size=%d sha256digest=%s" % (
                esc(rel), now, "" if mode == 0o644 else " mode=%o" % mode, st.st_size, digest))
    return gzip.compress(("\n".join(lines) + "\n").encode(), mtime=now)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("root")
    ap.add_argument("out")
    ap.add_argument("--name", required=True)
    ap.add_argument("--version", required=True)
    ap.add_argument("--pkgrel", default="1")
    ap.add_argument("--desc", required=True)
    ap.add_argument("--url", required=True)
    ap.add_argument("--license", default="MIT")
    ap.add_argument("--packager", default="Ward contributors")
    ap.add_argument("--depend", action="append", default=[])
    ap.add_argument("--optdepend", action="append", default=[])
    ap.add_argument("--install")
    a = ap.parse_args()
    now = int(os.environ.get("SOURCE_DATE_EPOCH", time.time()))

    entries, size = [], 0
    for dirpath, dirs, files in os.walk(a.root):
        dirs.sort()
        for n in sorted(dirs + files):
            full = os.path.join(dirpath, n)
            entries.append((full, os.path.relpath(full, a.root)))
            if os.path.isfile(full) and not os.path.islink(full):
                size += os.path.getsize(full)

    info = ["# Generated by Ward's packaging/mkarch.py",
            "pkgname = %s" % a.name, "pkgbase = %s" % a.name, "pkgver = %s-%s" % (a.version, a.pkgrel),
            "pkgdesc = %s" % a.desc, "url = %s" % a.url, "builddate = %d" % now, "packager = %s" % a.packager,
            "size = %d" % size, "arch = any", "license = %s" % a.license]
    info += ["depend = %s" % d for d in a.depend]
    info += ["optdepend = %s" % d for d in a.optdepend]
    meta = {".PKGINFO": ("\n".join(info) + "\n").encode()}
    if a.install:
        with open(a.install, "rb") as fh:
            meta[".INSTALL"] = fh.read()
    meta[".MTREE"] = _mtree(a.root, entries, now, dict(meta))

    def norm(ti: tarfile.TarInfo) -> tarfile.TarInfo:
        ti.uid = ti.gid = 0
        ti.uname = ti.gname = "root"
        ti.mtime = now
        return ti

    with tarfile.open(a.out, "w:xz", format=tarfile.PAX_FORMAT) as tf:
        for name, data in meta.items():
            ti = tarfile.TarInfo(name)
            ti.size, ti.mode = len(data), 0o644
            tf.addfile(norm(ti), io.BytesIO(data))
        for full, rel in entries:
            tf.add(full, arcname=rel, filter=norm, recursive=False)
    print(a.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
